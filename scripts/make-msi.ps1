[CmdletBinding()]
param(
    [string]$DistDir = 'dist\winTTSas',
    [string]$Output = '',
    [switch]$SkipPublish
)

$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
$dist = Join-Path $root $DistDir
$installer = Join-Path $root 'installer'
$generated = Join-Path $installer 'generated.wxs'

if (-not $SkipPublish -and -not (Test-Path (Join-Path $dist 'winTTSas.exe'))) {
    throw "Publish first: .\scripts\publish.ps1 (missing $(Join-Path $dist 'winTTSas.exe'))"
}

if (-not (Test-Path (Join-Path $dist 'winTTSas-server.exe'))) {
    throw "winTTSas-server.exe is missing from $dist"
}

$wix = Get-Command wix -ErrorAction SilentlyContinue
if (-not $wix) {
    throw @'
The WiX tool was not found. Install it once:
  dotnet tool install --global wix --version 5.0.2
  wix extension add -g WixToolset.UI.wixext/5.0.2
  wix extension add -g WixToolset.Util.wixext/5.0.2
'@
}

$buildInfo = Get-Content (Join-Path $root 'src\WinTtsAs.Core\BuildInfo.cs') -Raw
if ($buildInfo -notmatch 'Version\s*=\s*"([0-9]+\.[0-9]+\.[0-9]+)"') {
    throw 'Could not read the version from src\WinTtsAs.Core\BuildInfo.cs'
}

$version = $Matches[1]
if ([string]::IsNullOrWhiteSpace($Output)) {
    $Output = Join-Path $root "dist\winTTSas-$version-x64.msi"
}

function ConvertTo-WixId([string]$value) {
    $clean = [regex]::Replace($value, '[^A-Za-z0-9_.]', '_')
    if ($clean.Length -gt 60) {
        $clean = $clean.Substring(0, 60)
    }

    return $clean
}

function ConvertTo-XmlText([string]$value) {
    return [System.Security.SecurityElement]::Escape($value)
}

# Relative paths, sorted, so component IDs and the package stay reproducible.
$files = Get-ChildItem $dist -Recurse -File |
    ForEach-Object { [pscustomobject]@{
        Relative = [IO.Path]::GetRelativePath($dist, $_.FullName).Replace('\', '/')
        Full = $_.FullName
    } } |
    Sort-Object Relative

if ($files.Count -eq 0) {
    throw "No files found under $dist"
}

# Directory tree, keyed by relative path ('' is APPLICATIONFOLDER).
$directories = @{ '' = $null }
foreach ($file in $files) {
    $segments = $file.Relative -split '/'
    $path = ''
    for ($i = 0; $i -lt $segments.Count - 1; $i++) {
        $path = if ($path) { "$path/$($segments[$i])" } else { $segments[$i] }
        if (-not $directories.ContainsKey($path)) {
            $directories[$path] = $null
        }
    }
}

$directoryId = @{ '' = 'APPLICATIONFOLDER' }
foreach ($path in $directories.Keys) {
    if ($path -eq '') { continue }
    $directoryId[$path] = 'D_' + (ConvertTo-WixId ($path.Replace('/', '_')))
}

# Nested <Directory> authoring, parents before children.
$sb = [System.Text.StringBuilder]::new()
$null = $sb.AppendLine('<?xml version="1.0" encoding="utf-8"?>')
$null = $sb.AppendLine('<!-- Generated by scripts\make-msi.ps1 from ' + $DistDir + '. Do not edit. -->')
$null = $sb.AppendLine('<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">')
$null = $sb.AppendLine('  <Fragment>')
$null = $sb.AppendLine('    <DirectoryRef Id="APPLICATIONFOLDER">')

$ordered = $directories.Keys | Where-Object { $_ -ne '' } | Sort-Object { ($_ -split '/').Count }, { $_ }
foreach ($path in $ordered) {
    $segments = $path -split '/'
    $indent = '      ' + ('  ' * ($segments.Count - 1))
    $null = $sb.AppendLine("$indent<Directory Id=""$($directoryId[$path])"" Name=""$(ConvertTo-XmlText $segments[-1])"">")
}

foreach ($path in ($ordered | Sort-Object { ($_ -split '/').Count } -Descending)) {
    $segments = $path -split '/'
    $indent = '      ' + ('  ' * ($segments.Count - 1))
    $null = $sb.AppendLine("$indent</Directory>")
}

$null = $sb.AppendLine('    </DirectoryRef>')
$null = $sb.AppendLine('  </Fragment>')
$null = $sb.AppendLine('  <Fragment>')
$null = $sb.AppendLine('    <ComponentGroup Id="AppFiles">')

$index = 0
foreach ($file in $files) {
    $index++
    $relative = $file.Relative
    $name = ($relative -split '/')[-1]
    $parent = if ($relative.Contains('/')) {
        $relative.Substring(0, $relative.LastIndexOf('/'))
    } else {
        ''
    }

    $componentId = 'cmp_' + $index.ToString('0000')
    $fileId = 'fil_' + $index.ToString('0000')
    $source = ConvertTo-XmlText $file.Full

    if ($name -eq 'winTTSas.exe') {
        $fileId = 'WinTtsAsCliExe'
    }

    $null = $sb.AppendLine("      <Component Id=""$componentId"" Guid=""*"" Directory=""$($directoryId[$parent])"">")
    $null = $sb.AppendLine("        <File Id=""$fileId"" Source=""$source"" KeyPath=""yes"" />")
    $null = $sb.AppendLine('      </Component>')
}

$null = $sb.AppendLine('    </ComponentGroup>')
$null = $sb.AppendLine('  </Fragment>')
$null = $sb.AppendLine('</Wix>')

[IO.File]::WriteAllText($generated, $sb.ToString(), [Text.UTF8Encoding]::new($false))

Write-Host "winTTSas ${version}: $($files.Count) files, $($directories.Count - 1) folders"

& $wix.Source build `
    (Join-Path $installer 'winTTSas.wxs') `
    $generated `
    -arch x64 `
    -ext WixToolset.UI.wixext `
    -ext WixToolset.Util.wixext `
    -d "Version=$version" `
    -d "InstallerDir=$installer" `
    -o $Output

if ($LASTEXITCODE -ne 0) {
    throw "wix build failed with exit code $LASTEXITCODE"
}

$size = (Get-Item $Output).Length
Write-Host ("Wrote {0} ({1:N0} MB)" -f $Output, ($size / 1MB))
